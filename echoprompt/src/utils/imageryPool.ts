/* ========== 获取函数 ========== */

export function getRandomSceneByStyle(style?: ShortReplyStyle): ImageryScene {
  const pool = style
    ? imageryScenes.filter((s) => s.style === style)
    : imageryScenes;
  return pool[Math.floor(Math.random() * pool.length)];
}

export function getRandomSceneWithFragments(): string {
  const scene = getRandomSceneByStyle();
  const frag = scene.fragments[Math.floor(Math.random() * scene.fragments.length)];
  return frag;
}

export function getSceneById(id: string): ImageryScene | undefined {
  return imageryScenes.find((s) => s.id === id);
}
